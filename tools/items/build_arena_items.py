def full_name(component):
    return component if component.startswith("item_") else "item_arena_" + component


def join(parts):
    return parts[0] if len(parts) == 1 else ", ".join(parts[:-1]) + " and " + parts[-1]


def number(value):
    return str(int(value)) if float(value).is_integer() else str(value)


def priced(items):
    """Fill in the price of every combined item from its components and scroll."""
    by_key = {entry["key"]: entry for entry in items}
    dota_prices = {"item_boots": 500}

    def price(key):
        if key.startswith("item_"):
            return dota_prices[key]
        entry = by_key[key]
        if entry["cost"] is None:
            components, scroll = entry["recipe"]
            entry["cost"] = sum(price(component) for component in components) + scroll
        return entry["cost"]

    for entry in items:
        price(entry["key"])
    return items


def quality(entry):
    if entry["consume"]:
        return "consumable"
    cost = entry["cost"]
    if entry["section"] == "secretshop":
        return "secret_shop"
    return "component" if cost < 3000 and not entry["recipe"] else "common" if cost < 4000 \
        else "rare" if cost < 9000 else "epic" if cost < 14000 else "artifact"


def description(entry, items=()):
    """The tooltip body: one headed paragraph per thing the item does."""
    values = entry["values"]
    titles = entry.get("titles", {})
    blocks = []
    if entry["consume"]:
        kind = entry["consume"]
        text = CONSUME_TEXT.get(kind)
        if kind == "potion_buff":
            text = "For %potion_duration% seconds you have " + join(
                [("+" if values[name] > 0 else "") + label for name, label in POTION_BUFFS if name in values]) + "."
        blocks.append(("Use: " + ("Study" if kind.startswith("tome") else "Ignite" if kind == "potion_ember" else "Drink"), text))
    if entry["active"]:
        kind = entry["active"][0]
        if kind == "smite":
            heading = "Sunlance"
            text = "Strikes an enemy within %active_range% for %active_damage% magic damage" + (
                " and stuns it for %active_stun% seconds." if values.get("active_stun") else ".") + \
                " Does not affect spell-immune enemies."
        else:
            heading, text = ACTIVE_TEXT[kind]
        blocks.append(("Active: " + titles.get(kind, heading), text))
    for name in entry["mech"]:
        if name == "aura_ally":
            blocks.append(("Aura: " + titles.get(name, "Blessing"), "You and allies within %aura_radius% gain " + join(
                [label for key, label in AURA_ALLY if key in values]) + "."))
        elif name == "aura_enemy":
            blocks.append(("Aura: " + titles.get(name, "Brimstone"),
                           "Enemies within %aura_radius% burn for %aura_burn_dps% magic damage each second" + (
                               " and lose %aura_armor_reduction% armor." if "aura_armor_reduction" in values else ".")))
        elif name in ("lifesteal", "spell_lifesteal") and name not in titles:
            continue  # shown as a stat line only
        else:
            heading, text = MECHANIC_TEXT[name]
            blocks.append(("Passive: " + titles.get(name, heading), text))
    blocks += entry.get("notes", [])
    made = [other["name"] for other in items if other["recipe"] and entry["key"] in other["recipe"][0]]
    if made:
        blocks.append(("Forging", "Used to make " + join(made) + "."))
    return "\\n".join("<h1>%s</h1>%s" % block for block in blocks)


def kv_block(name, pairs, indent=1):
    tab = "\t" * indent
    lines = [tab + '"%s"' % name, tab + "{"]
    for key, value in pairs:
        if isinstance(value, list):
            lines += kv_block(key, value, indent + 1)
        else:
            lines.append('%s\t"%s"\t\t"%s"' % (tab, key, value))
    lines.append(tab + "}")
    return lines


def build_kv(items):
    out = ['// Generated by tools/items/build_arena_items.py from tools/items/arena_items.py. Do not edit by hand.',
           '"DOTAAbilities"', "{"]
    for index, entry in enumerate(items):
        name = "item_arena_" + entry["key"]
        pairs = [("ID", FIRST_ITEM_ID + index), ("BaseClass", "item_lua"), ("ScriptFile", SCRIPT),
                 ("AbilityTextureName", "arena/" + entry["key"])]
        values = dict(entry["values"])
        if entry["consume"]:
            pairs += [("AbilityBehavior", "DOTA_ABILITY_BEHAVIOR_NO_TARGET | DOTA_ABILITY_BEHAVIOR_IMMEDIATE"),
                      ("AbilityCastPoint", "0.0"),
                      ("AbilityCooldown", "1.0" if entry["consume"].startswith("tome") else "12.0"),
                      ("ItemStackable", 1), ("ItemPermanent", 0), ("ItemInitialCharges", 1),
                      ("ItemShareability", "ITEM_FULLY_SHAREABLE"), ("ArenaConsume", entry["consume"])]
        elif entry["active"]:
            kind, cooldown, mana = entry["active"]
            if kind == "smite":
                pairs += [("AbilityBehavior", "DOTA_ABILITY_BEHAVIOR_UNIT_TARGET"),
                          ("AbilityUnitTargetTeam", "DOTA_UNIT_TARGET_TEAM_ENEMY"),
                          ("AbilityUnitTargetType", "DOTA_UNIT_TARGET_HERO | DOTA_UNIT_TARGET_BASIC"),
                          ("AbilityUnitDamageType", "DAMAGE_TYPE_MAGICAL"),
                          ("SpellImmunityType", "SPELL_IMMUNITY_ENEMIES_NO"),
                          ("AbilityCastRange", number(values["active_range"]))]
            else:
                pairs += [("AbilityBehavior", "DOTA_ABILITY_BEHAVIOR_NO_TARGET | DOTA_ABILITY_BEHAVIOR_IMMEDIATE")]
            pairs += [("AbilityCastPoint", "0.0"), ("AbilityCooldown", "%.1f" % cooldown),
                      ("AbilityManaCost", mana), ("ArenaActive", kind)]
        else:
            pairs += [("AbilityBehavior", "DOTA_ABILITY_BEHAVIOR_PASSIVE")]
        pairs += [("ItemCost", entry["cost"]), ("ItemQuality", quality(entry)),
                  ("ItemAliases", entry["name"].lower().replace("'", "")),
                  ("ItemPurchasable", 1), ("ItemSellable", 1), ("ItemDroppable", 1)]
        if entry["mech"]:
            pairs.append(("ArenaMechanics", " ".join(entry["mech"])))
        pairs.append(("AbilityValues", [(key, number(value)) for key, value in values.items()]))
        out += [""] + kv_block(name, pairs)
        if entry["recipe"]:
            components, scroll = entry["recipe"]
            out += [""] + kv_block("item_recipe_arena_" + entry["key"], [
                ("ID", FIRST_RECIPE_ID + index), ("BaseClass", "item_datadriven"),
                ("AbilityTextureName", "item_recipe"), ("ItemRecipe", 1), ("ItemCost", scroll),
                ("ItemShopTags", ""), ("ItemResult", name),
                ("ItemRequirements", [("01", ";".join(full_name(component) for component in components))])])
    return "\n".join(out + ["}", ""])


def build_tokens(items):
    tokens = []
    for entry in items:
        base = "DOTA_Tooltip_ability_item_arena_" + entry["key"]
        tokens.append((base, entry["name"]))
        text = description(entry, items)
        if text:
            tokens.append((base + "_Description", text))
        tokens.append((base + "_Lore", entry["lore"]))
        tokens += [(base + "_" + name, STAT_LINES[name]) for name in entry["values"] if name in STAT_LINES]
        if entry["recipe"]:
            recipe = "DOTA_Tooltip_ability_item_recipe_arena_" + entry["key"]
            tokens += [(recipe, "Recipe: " + entry["name"]), (recipe + "_Description", "Combines into " + entry["name"] + ".")]
    return tokens


def replace_block(text, block, newline, indent):
    """Swap the marked block for `block`, or add it before the last two closing braces."""
    lines = [indent + BEGIN] + [indent + line for line in block] + [indent + END]
    body = newline.join(lines) + newline
    pattern = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"[ \t]*\r?\n", re.S)
    if pattern.search(text):
        return pattern.sub(lambda match: body, text, count=1)
    last = text.rindex("}")
    outer = text.rindex("}", 0, last)
    start = text.rindex("\n", 0, outer) + 1
    return text[:start] + body + text[start:]


# Dota's own "Sell Price: <b>N</b>" is shown in a label that does not render markup, so the
# tags appear as text on every item. The override drops them.
EXTRA_TOKENS = [("DOTA_HUD_Item_Tooltip_Sell_Price", "Sell Price: {u:sell_price}")]


def build_localization(text, tokens):
    newline = "\r\n" if "\r\n" in text else "\n"
    block = ['"%s"\t\t"%s"' % (key, value.replace('"', '\\"')) for key, value in tokens]
    return replace_block(text, block, newline, "\t\t")


def build_shop(text, items):
    newline = "\r\n" if "\r\n" in text else "\n"
    marked = re.compile(r"[ \t]*// arena items begin.*?// arena items end[ \t]*\r?\n", re.S)
    text = marked.sub("", text)
    for section in dict.fromkeys(entry["section"] for entry in items):
        match = re.search(r'^[ \t]*"%s"[ \t]*\r?\n[ \t]*\{' % re.escape(section), text, re.M)
        assert match, "shop section missing: " + section
        close = text.index("}", match.end())
        start = text.rindex("\n", 0, close) + 1
        lines = ["\t\t// arena items begin (generated by tools/items/build_arena_items.py)"]
        lines += ['\t\t"item"\t\t"item_arena_%s"' % entry["key"] for entry in items if entry["section"] == section]
        lines.append("\t\t// arena items end")
        text = text[:start] + newline.join(lines) + newline + text[start:]
    return text


def build_icon_jobs(items):
    return json.dumps([{"name": entry["key"], "model": "gpt-image-2.5-flare", "size": "1536x1024",
                        "quality": "medium", "prompt": ICON_STYLE.format(subject=entry["icon"])}
                       for entry in items], indent=2) + "\n"


def main():
    check = "--check" in sys.argv
    items = priced(ITEMS)
    keys = [entry["key"] for entry in items]
    assert len(set(keys)) == len(keys), "duplicate item key"
    for entry in items:
        for component in (entry["recipe"] or ([], 0))[0]:
            assert component.startswith("item_") or component in keys, (entry["key"], component)

    outputs = [(KV_PATH, "utf-8", build_kv(items)),
               (ICON_JOBS, "utf-8", build_icon_jobs(items)),
               (SHOP_PATH, "utf-8", build_shop(SHOP_PATH.read_bytes().decode("utf-8"), items))]
    tokens = EXTRA_TOKENS + build_tokens(items)
    for path, encoding in LOC_PATHS:
        outputs.append((path, encoding, build_localization(path.read_bytes().decode(encoding), tokens)))

    stale = []
    for path, encoding, text in outputs:
        # Line endings are ignored when comparing: git checks these files out with CRLF on Windows.
        current = path.read_bytes().decode(encoding) if path.exists() else None
        if current is not None and current.replace("\r\n", "\n") == text.replace("\r\n", "\n"):
            continue
        stale.append(path)
        if not check:
            data = text.encode("utf-16-le") if encoding == "utf-16" else text.encode("utf-8")
            data = {"utf-16": b"\xff\xfe", "utf-8-sig": b"\xef\xbb\xbf"}.get(encoding, b"") + data
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    names = ", ".join(str(path.relative_to(REPO)) for path in stale) or "nothing"
    print(("out of date: " if check else "wrote: ") + names)
    print("%d items, %d recipes, %d tooltip lines" % (len(items), sum(1 for e in items if e["recipe"]), len(tokens)))
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
