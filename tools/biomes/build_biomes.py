#!/usr/bin/env python3
"""Merge the biome tooltip fragments into the game's localization files.

    python tools/biomes/build_biomes.py [--check]

Reads tools/biomes/tooltips/shared.txt and tools/biomes/tooltips/<biome>.txt for every biome in
ArenaBiomes.NAMES (game/angel_arena/scripts/vscripts/arena/core/biomes.lua), checks each
biome's files against each other (see biomelib.biome_problems), and writes all tokens into one
marked block in:
  game/angel_arena/resource/addon_english.txt      (UTF-16, what the game reads)
  content/angel_arena/addon_english_utf8.txt       (UTF-8 mirror with the same tokens)

With --check nothing is written; the script exits non-zero if a file is out of date or a biome
has a problem. A missing fragment is fine: that biome simply adds no tokens yet.
"""
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True  # no __pycache__ beside the tools
sys.path.insert(0, str(Path(__file__).resolve().parent))
import biomelib  # noqa: E402

BEGIN = "// ARENA BIOMES BEGIN (generated by tools/biomes/build_biomes.py, do not edit by hand)"
END = "// ARENA BIOMES END"


def replace_block(text, lines, newline, indent="\t\t"):
    """Swap the marked block for `lines`, or add it before the last two closing braces."""
    body = newline.join([indent + BEGIN] + [indent + line for line in lines] + [indent + END]) + newline
    pattern = re.compile(r"[ \t]*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"[ \t]*\r?\n", re.S)
    if pattern.search(text):
        return pattern.sub(lambda match: body, text, count=1)
    last = text.rindex("}")
    outer = text.rindex("}", 0, last)
    start = text.rindex("\n", 0, outer) + 1
    return text[:start] + body + text[start:]


def outside_block(text):
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    return pattern.sub("", text)


def build(text, tokens):
    newline = "\r\n" if "\r\n" in text else "\n"
    lines = ['"%s"\t\t"%s"' % (token, value) for token, value in tokens]
    return replace_block(text, lines, newline)


def main():
    check = "--check" in sys.argv
    tokens, problems = biomelib.all_tokens()
    lookup = dict(tokens)
    for biome in biomelib.biome_names():
        problems += ["%s: %s" % (biome, problem) for problem in biomelib.biome_problems(biome, lookup)]

    outputs = []
    for path, encoding in biomelib.LOC_PATHS:
        current = path.read_bytes().decode(encoding)
        rest = outside_block(current)
        for token, _ in tokens:
            if re.search(r'^\s*"%s"\s' % re.escape(token), rest, re.M):
                problems.append("%s is also defined outside the biome block in %s" % (token, biomelib.rel(path)))
        outputs.append((path, encoding, current, build(current, tokens)))

    stale = []
    for path, encoding, current, text in outputs:
        # Line endings are ignored when comparing: git checks these files out with CRLF on Windows.
        if current.replace("\r\n", "\n") == text.replace("\r\n", "\n"):
            continue
        stale.append(path)
        if not check and not problems:
            data = text.encode("utf-16-le") if encoding == "utf-16" else text.encode("utf-8")
            data = {"utf-16": b"\xff\xfe", "utf-8-sig": b"\xef\xbb\xbf"}.get(encoding, b"") + data
            path.write_bytes(data)

    for problem in problems:
        print("problem: " + problem)
    if problems:
        print("%d problem(s); %s" % (len(problems), "nothing written" if not check else "fix them first"))
        return 1
    names = ", ".join(biomelib.rel(path) for path in stale) or "nothing"
    print(("out of date: " if check else "wrote: ") + names)
    print("%d tooltip lines from %d biomes" % (len(tokens), len(biomelib.biome_names())))
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
